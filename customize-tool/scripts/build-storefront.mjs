/**
 * Bundle the storefront runtime (customize-tool/storefront/index.ts) into the
 * Shopify theme asset customize-tool/shopify/assets/ct-customizer.js.
 *
 *   npm run build:ct-storefront
 *
 * It shares lib/compositor.ts with the editor, so rebuild after changing any
 * rendering code and re-upload the asset to the theme.
 */

import { build } from "esbuild";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const outfile = path.join(root, "shopify", "assets", "ct-customizer.js");

await build({
  entryPoints: [path.join(root, "storefront", "index.ts")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["es2020"],
  outfile,
  minify: true,
  legalComments: "none",
  banner: { js: "/* Customize Tool storefront runtime — generated by customize-tool/scripts/build-storefront.mjs, do not edit. */" },
  // config.ts reads this for the server; the browser bundle never uses it.
  define: { "process.env.NEXT_PUBLIC_DB_SCHEMA": '""' },
});

console.log(`[ct] built ${path.relative(process.cwd(), outfile)}`);
